"""
Layout specification -- the declarative "profile" an AI (or a human) can
write down about a question-bank layout, and that deterministic code can
execute.

Why a declarative spec instead of "let the AI extract the questions":

  - The AI never writes question content. It only describes structure
    ("stems look like `Q3.`", "options look like `(b)`", "the key starts
    under a line reading `Model answer`"). Every character of every
    extracted question therefore comes from a real source line, and
    provenance is exact by construction.
  - A spec is reusable. Once validated on a document it is stored as a
    layout profile and applied to later documents with the same layout
    without another AI call.
  - A spec cannot express anything dangerous. It is not code and not a
    raw regex: patterns are generated by this module from a small fixed
    grammar (marker style + escaped literals), so there is no ReDoS
    surface and no way to smuggle in behaviour the engine doesn't have.

Nothing in here touches documents. layout_engine.py executes a spec;
layout_validation.py decides whether the result can be trusted.
"""

from __future__ import annotations

import hashlib
import json
import re
import unicodedata
from dataclasses import dataclass
from typing import Literal, Optional

from pydantic import BaseModel, ConfigDict, Field, field_validator, model_validator

SPEC_SCHEMA_VERSION = 1

CLOSER_ALPHABET = "-.):\u00b7]|"
_MAX_LITERAL = 60

ContentKind = Literal["mcq", "fill_in_blank", "matching"]
SectionKind = Literal["mcq", "fill_in_blank", "matching", "answer_key"]


class _Strict(BaseModel):
    model_config = ConfigDict(extra="forbid")


def normalize_literal(text: str) -> str:
    """Normal form used to compare header lines with spec literals:
    NFKC, lower-case, collapsed whitespace, surrounding punctuation and
    decoration stripped. Tolerant of case and trailing dots/colons, not of
    different words."""
    s = unicodedata.normalize("NFKC", text).lower()
    s = re.sub(r"\s+", " ", s).strip(" \t.:;-\u2014\u2013_*#|")
    return s


def _listify(v):
    if v is None:
        return []
    if isinstance(v, str):
        return [v] if v.strip() else []
    return list(v)


def _closer_string(v):
    # Models like to answer with ["." , ")"] or ". )" -- accept, normalise.
    if isinstance(v, (list, tuple)):
        v = "".join(str(x) for x in v)
    if isinstance(v, str):
        v = "".join(ch for ch in v if not ch.isspace())
        out = []
        for ch in v:  # de-duplicate, keep order
            if ch not in out:
                out.append(ch)
        v = "".join(out)
    return v


def _check_closers(v: str, *, allow_empty: bool = False) -> str:
    if not v and not allow_empty:
        raise ValueError("closers must be a non-empty string of characters from " + CLOSER_ALPHABET)
    bad = [ch for ch in v if ch not in CLOSER_ALPHABET]
    if bad:
        raise ValueError(f"closers may only contain {CLOSER_ALPHABET!r}, got {bad!r}")
    return v


class QuestionMarker(_Strict):
    """How a question stem line starts: [prefix][open]NUMBER<closer>+ text."""

    prefix: str = Field("", max_length=20)
    open: Literal["", "(", "["] = ""
    closers: str = "-.):"
    evidence: list[str] = Field(default_factory=list)

    @field_validator("closers", mode="before")
    @classmethod
    def _c(cls, v):
        return _closer_string(v)

    @field_validator("closers")
    @classmethod
    def _c2(cls, v):
        return _check_closers(v)

    @field_validator("evidence", mode="before")
    @classmethod
    def _e(cls, v):
        return _listify(v)

    @field_validator("prefix")
    @classmethod
    def _p(cls, v):
        if "\n" in v or "\r" in v:
            raise ValueError("prefix must be a single-line literal")
        return v.strip()

    @model_validator(mode="after")
    def _o(self):
        if self.open == "(" and ")" not in self.closers:
            raise ValueError("open='(' needs ')' among closers")
        if self.open == "[" and "]" not in self.closers:
            raise ValueError("open='[' needs ']' among closers")
        return self


class OptionMarker(_Strict):
    """How an option line starts: [open]LETTER<closer> text."""

    case: Literal["lower", "upper", "either"] = "lower"
    open: Literal["", "("] = ""
    closers: str = ".)"
    max_label: str = Field("f", pattern=r"^[a-hA-H]$")
    evidence: list[str] = Field(default_factory=list)

    @field_validator("closers", mode="before")
    @classmethod
    def _c(cls, v):
        return _closer_string(v)

    @field_validator("closers")
    @classmethod
    def _c2(cls, v):
        return _check_closers(v)

    @field_validator("evidence", mode="before")
    @classmethod
    def _e(cls, v):
        return _listify(v)

    @model_validator(mode="after")
    def _o(self):
        if self.open == "(" and ")" not in self.closers:
            raise ValueError("open='(' needs ')' among closers")
        return self


class SectionHeader(_Strict):
    """A literal header line that switches content kind / starts a key."""

    header: str = Field(..., min_length=1, max_length=_MAX_LITERAL)
    kind: SectionKind
    evidence: list[str] = Field(default_factory=list)

    @field_validator("evidence", mode="before")
    @classmethod
    def _e(cls, v):
        return _listify(v)

    @field_validator("header")
    @classmethod
    def _h(cls, v):
        if "\n" in v or "\r" in v:
            raise ValueError("header must be a single line")
        if not normalize_literal(v):
            raise ValueError("header is empty after normalisation")
        return v.strip()


class Grouping(_Strict):
    mode: Literal["none", "heading_restart"] = "none"


class AnswerKey(_Strict):
    mode: Literal["none", "section", "inline_label", "marked_option"] = "none"
    # section mode: entries like "12-b" / "12. b" / "12 | b"
    separators: str = "-."
    allow_space: bool = False
    grouped: bool = False  # key block repeats chapter headings
    # inline_label mode: a line like "Answer: b" after each question
    inline_prefixes: list[str] = Field(default_factory=list)
    # marked_option mode: the correct option carries this literal mark
    option_mark: str = Field("", max_length=12)
    option_mark_position: Literal["suffix", "prefix"] = "suffix"
    evidence: list[str] = Field(default_factory=list)

    @field_validator("separators", mode="before")
    @classmethod
    def _s(cls, v):
        return _closer_string(v)

    @field_validator("separators")
    @classmethod
    def _s2(cls, v):
        return _check_closers(v, allow_empty=True)

    @field_validator("evidence", "inline_prefixes", mode="before")
    @classmethod
    def _e(cls, v):
        return _listify(v)

    @field_validator("inline_prefixes")
    @classmethod
    def _ip(cls, v):
        if len(v) > 6:
            raise ValueError("at most 6 inline prefixes")
        for p in v:
            if not p.strip() or len(p) > 20 or "\n" in p:
                raise ValueError("inline prefixes must be short single-line literals")
        return [p.strip() for p in v]

    @model_validator(mode="after")
    def _m(self):
        if self.mode == "section" and not self.separators and not self.allow_space:
            raise ValueError("section key needs at least one separator (or allow_space)")
        if self.mode == "inline_label" and not self.inline_prefixes:
            raise ValueError("inline_label key needs inline_prefixes")
        if self.mode == "marked_option" and not self.option_mark.strip():
            raise ValueError("marked_option key needs option_mark")
        return self


class LayoutSpec(_Strict):
    schema_version: int = SPEC_SCHEMA_VERSION
    expressible: bool = True
    question_marker: Optional[QuestionMarker] = None
    option_marker: Optional[OptionMarker] = None
    sections: list[SectionHeader] = Field(default_factory=list)
    default_content_kind: Optional[ContentKind] = None
    grouping: Grouping = Field(default_factory=Grouping)
    answer_key: AnswerKey = Field(default_factory=AnswerKey)
    notes: str = Field("", max_length=400)

    @field_validator("sections", mode="before")
    @classmethod
    def _s(cls, v):
        return v or []

    @model_validator(mode="after")
    def _consistency(self):
        if not self.expressible:
            return self
        if self.question_marker is None:
            raise ValueError("question_marker is required when expressible")
        content_kinds = {s.kind for s in self.sections if s.kind != "answer_key"}
        if self.default_content_kind:
            content_kinds.add(self.default_content_kind)
        if not content_kinds:
            raise ValueError("no content kind: give default_content_kind or a content section header")
        if "mcq" in content_kinds and self.option_marker is None:
            raise ValueError("option_marker is required when MCQ content exists")
        ak = self.answer_key
        if ak.mode == "section" and not any(s.kind == "answer_key" for s in self.sections):
            raise ValueError("answer_key.mode='section' needs a section header with kind 'answer_key'")
        if ak.mode != "section" and any(s.kind == "answer_key" for s in self.sections):
            raise ValueError("an answer_key section header requires answer_key.mode='section'")
        if ak.grouped and self.grouping.mode != "heading_restart":
            raise ValueError("answer_key.grouped requires grouping.mode='heading_restart'")
        if ak.mode in ("inline_label", "marked_option") and "mcq" not in content_kinds and ak.mode == "marked_option":
            raise ValueError("marked_option applies to MCQ content only")
        seen = {}
        for s in self.sections:
            n = normalize_literal(s.header)
            if n in seen and seen[n] != s.kind:
                raise ValueError(f"header {s.header!r} listed with two different kinds")
            seen[n] = s.kind
        return self

    # -- identity ---------------------------------------------------------

    def canonical_dict(self) -> dict:
        """The reusable part of the spec: no evidence refs (they point into
        one specific document), no free-text notes, normalised literals,
        order-independent sections."""
        d = self.model_dump(mode="json")
        for key in ("question_marker", "option_marker"):
            if d.get(key):
                d[key].pop("evidence", None)
        d["answer_key"].pop("evidence", None)
        d.pop("notes", None)
        secs = []
        for s in d["sections"]:
            secs.append({"header": normalize_literal(s["header"]), "kind": s["kind"]})
        d["sections"] = sorted(secs, key=lambda x: (x["header"], x["kind"]))
        d["answer_key"]["inline_prefixes"] = sorted(p.lower() for p in d["answer_key"]["inline_prefixes"])
        return d

    def profile_id(self) -> str:
        blob = json.dumps(self.canonical_dict(), sort_keys=True, ensure_ascii=False)
        return "LP-" + hashlib.sha1(blob.encode("utf-8")).hexdigest()[:12]

    def evidence_refs(self) -> dict[str, list[str]]:
        out: dict[str, list[str]] = {}
        if self.question_marker:
            out["question_marker"] = list(self.question_marker.evidence)
        if self.option_marker:
            out["option_marker"] = list(self.option_marker.evidence)
        for i, s in enumerate(self.sections):
            out[f"section[{i}]:{s.header}"] = list(s.evidence)
        out["answer_key"] = list(self.answer_key.evidence)
        return out

    def stripped(self) -> "LayoutSpec":
        """Copy with evidence/notes removed -- what a stored profile keeps."""
        d = self.model_dump(mode="json")
        for key in ("question_marker", "option_marker"):
            if d.get(key):
                d[key]["evidence"] = []
        d["answer_key"]["evidence"] = []
        for s in d["sections"]:
            s["evidence"] = []
        d["notes"] = ""
        return LayoutSpec(**d)


# ---------------------------------------------------------------------------
# Compilation: spec -> regexes, from the fixed grammar only
# ---------------------------------------------------------------------------


def _cls(chars: str) -> str:
    return "[" + "".join(re.escape(c) for c in chars) + "]"


def stem_regex(m: QuestionMarker) -> re.Pattern:
    pre = (re.escape(m.prefix) + r"\s*") if m.prefix else ""
    op = (re.escape(m.open) + r"\s*") if m.open else ""
    return re.compile(rf"^{pre}{op}(\d{{1,3}})\s*{_cls(m.closers)}+\s*(.*)$", re.I)


def option_regex(m: OptionMarker) -> re.Pattern:
    hi = m.max_label.lower()
    if m.case == "lower":
        letters = f"a-{hi}"
    elif m.case == "upper":
        letters = f"A-{hi.upper()}"
    else:
        letters = f"a-{hi}A-{hi.upper()}"
    op = (re.escape(m.open) + r"\s*") if m.open else ""
    return re.compile(rf"^{op}([{letters}])\s*{_cls(m.closers)}\s*(.*)$")


_ANSWER_LETTERS = r"[a-fA-F](?:\s*[&,]\s*[a-fA-F])*"


def key_token_regex(ak: AnswerKey) -> re.Pattern:
    sep = _cls(ak.separators) if ak.separators else None
    if sep and ak.allow_space:
        sepx = rf"(?:\s*{sep}\s*|\s+)"
    elif sep:
        sepx = rf"\s*{sep}\s*"
    else:
        sepx = r"\s+"
    return re.compile(rf"(\d{{1,3}}){sepx}({_ANSWER_LETTERS})\b")


def inline_label_regex(prefixes: list[str]) -> re.Pattern:
    alt = "|".join(re.escape(p) for p in sorted(prefixes, key=len, reverse=True))
    return re.compile(rf"^(?:{alt})\s*[:.\-=)]*\s*\(?({_ANSWER_LETTERS})\)?\.?\s*$", re.I)


def inline_text_regex(prefixes: list[str]) -> re.Pattern:
    alt = "|".join(re.escape(p) for p in sorted(prefixes, key=len, reverse=True))
    return re.compile(rf"^(?:{alt})\s*[:\-=]\s*(.+)$", re.I)


@dataclass
class CompiledSpec:
    spec: LayoutSpec
    stem_re: re.Pattern
    option_re: Optional[re.Pattern]
    header_kinds: dict  # normalised header text -> section kind
    key_token_re: Optional[re.Pattern]
    inline_re: Optional[re.Pattern]
    inline_text_re: Optional[re.Pattern]
    mark: str
    mark_position: str

    @property
    def grouped_mcq(self) -> bool:
        return self.spec.grouping.mode == "heading_restart"


def compile_spec(spec: LayoutSpec) -> CompiledSpec:
    if not spec.expressible or spec.question_marker is None:
        raise ValueError("cannot compile a spec that is not expressible")
    ak = spec.answer_key
    return CompiledSpec(
        spec=spec,
        stem_re=stem_regex(spec.question_marker),
        option_re=option_regex(spec.option_marker) if spec.option_marker else None,
        header_kinds={normalize_literal(s.header): s.kind for s in spec.sections},
        key_token_re=key_token_regex(ak) if ak.mode == "section" else None,
        inline_re=inline_label_regex(ak.inline_prefixes) if ak.mode == "inline_label" else None,
        inline_text_re=inline_text_regex(ak.inline_prefixes) if ak.mode == "inline_label" else None,
        mark=ak.option_mark.strip() if ak.mode == "marked_option" else "",
        mark_position=ak.option_mark_position,
    )
